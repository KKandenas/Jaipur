export type RandomSource = () => number; // returns a float in [0, 1)

export const defaultRandom: RandomSource = () => Math.random();

/** Deterministic RNG (mulberry32) so tests can reproduce a shuffle/deal. */
export function seededRandom(seed: number): RandomSource {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Fisher-Yates shuffle; does not mutate the input array. */
export function shuffled<T>(items: T[], random: RandomSource = defaultRandom): T[] {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
